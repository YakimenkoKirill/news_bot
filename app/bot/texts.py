def help_text() -> str:
    """Список команд с описаниями (тот же, что в меню Telegram)."""
    lines = ["<b>Команды</b>"]
    lines.extend(f"/{command} — {description}" for command, description in COMMANDS.items())
    return "\n".join(lines)


